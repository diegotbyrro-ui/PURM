create table if not exists public.purm_finance_entries (
  id uuid primary key default gen_random_uuid(),
  description text not null check (char_length(btrim(description)) between 1 and 220),
  kind text not null check (kind in ('income','expense','transfer_in','transfer_out')),
  amount_cents bigint not null check (amount_cents between 1 and 100000000000),
  category text not null default 'Outras despesas',
  account_label text not null default 'Conta principal',
  payment_method text not null default 'Outro',
  occurrence_date date not null,
  due_date date not null,
  settled_date date,
  status text not null default 'pending' check (status in ('pending','settled')),
  cash_effect boolean not null default false,
  source text not null default 'manual' check (source in ('manual','import_bank','import_card','secretary')),
  import_fingerprint text unique,
  notes text not null default '',
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint purm_finance_settlement_consistency check (
    (status='pending' and settled_date is null and cash_effect=false)
    or (status='settled' and settled_date is not null)
  )
);
create index if not exists purm_finance_period_idx on public.purm_finance_entries(occurrence_date desc);
create index if not exists purm_finance_due_idx on public.purm_finance_entries(status,due_date);
create index if not exists purm_finance_cash_idx on public.purm_finance_entries(settled_date, cash_effect);

create table if not exists public.purm_finance_audit (
  id bigint generated by default as identity primary key,
  entry_id uuid not null,
  action text not null check (action in ('INSERT','UPDATE','DELETE')),
  actor_id uuid,
  before_state jsonb,
  after_state jsonb,
  changed_at timestamptz not null default now()
);
create index if not exists purm_finance_audit_entry_idx on public.purm_finance_audit(entry_id,changed_at desc);

create table if not exists public.purm_secretary_events (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(btrim(title)) between 2 and 180),
  start_at timestamptz not null,
  end_at timestamptz not null,
  notes text not null default '',
  remind_day_before boolean not null default true,
  remind_hour_before boolean not null default true,
  google_event_id text,
  source text not null default 'carla' check(source in ('carla','manual','google')),
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  constraint purm_secretary_events_dates check (end_at > start_at)
);
create index if not exists purm_secretary_events_start_idx on public.purm_secretary_events(start_at);

-- Atualiza timestamps e cria auditoria imutavel de lancamentos financeiros.
create or replace function public.purm_finance_update_timestamp() returns trigger
language plpgsql set search_path='' as $$
begin
  new.created_at=old.created_at;
  new.created_by=old.created_by;
  new.updated_at=now();
  return new;
end;$$;

create or replace function public.purm_finance_audit_changes() returns trigger
language plpgsql security definer set search_path='' as $$
begin
  if tg_op='DELETE' then
    insert into public.purm_finance_audit(entry_id,action,actor_id,before_state)
    values(old.id,tg_op,(select auth.uid()),to_jsonb(old));
    return old;
  elsif tg_op='UPDATE' then
    insert into public.purm_finance_audit(entry_id,action,actor_id,before_state,after_state)
    values(new.id,tg_op,(select auth.uid()),to_jsonb(old),to_jsonb(new));
    return new;
  else
    insert into public.purm_finance_audit(entry_id,action,actor_id,after_state)
    values(new.id,tg_op,(select auth.uid()),to_jsonb(new));
    return new;
  end if;
end;$$;

-- Apenas triggers com nomes especificos desse novo modulo.
drop trigger if exists purm_finance_timestamp_trigger on public.purm_finance_entries;
create trigger purm_finance_timestamp_trigger before update on public.purm_finance_entries
for each row execute function public.purm_finance_update_timestamp();
drop trigger if exists purm_finance_audit_trigger on public.purm_finance_entries;
create trigger purm_finance_audit_trigger after insert or update or delete on public.purm_finance_entries
for each row execute function public.purm_finance_audit_changes();

alter table public.purm_finance_entries enable row level security;
alter table public.purm_finance_audit enable row level security;
alter table public.purm_secretary_events enable row level security;

